import { build } from 'esbuild';
import { inject } from 'postject';
import { execFileSync, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, '.build');
const bundlePath = path.join(outDir, 'amo.cjs');
const blobPath = path.join(outDir, 'amo.blob');
const configPath = path.join(outDir, 'sea-config.json');
const basePath = path.join(outDir, 'amo-base');
const binaryPath = path.join(root, 'amo');
const fuse = 'NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2';

fs.mkdirSync(outDir, { recursive: true });

await build({
  entryPoints: [path.join(root, 'src/cli/index.js')],
  outfile: bundlePath,
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node22',
  minify: true,
  sourcemap: false,
  logLevel: 'warning',
  legalComments: 'none'
});

fs.writeFileSync(configPath, JSON.stringify({
  main: bundlePath,
  output: blobPath,
  disableExperimentalSEAWarning: true,
  useSnapshot: false,
  useCodeCache: false
}, null, 2) + '\n');

execFileSync(process.execPath, ['--experimental-sea-config', configPath], { stdio: 'inherit' });

// AMO_NODE_BASE allows the SEA payload to be injected into a Node.js binary
// built for a different target architecture (cross-compilation). The payload
// itself is generated by the host Node.js with the matching version.
const nodeBinary = fs.realpathSync(process.env.AMO_NODE_BASE || process.execPath);
fs.copyFileSync(nodeBinary, basePath);
fs.chmodSync(basePath, 0o755);
try {
  const strip = spawnSync('strip', [basePath], { stdio: 'ignore' });
  if (strip.status !== 0) throw new Error('strip failed');
} catch { }

fs.copyFileSync(basePath, binaryPath);
fs.chmodSync(binaryPath, 0o755);

await inject(binaryPath, 'NODE_SEA_BLOB', fs.readFileSync(blobPath), { sentinelFuse: fuse });

const size = (fs.statSync(binaryPath).size / 1024 / 1024).toFixed(1);
console.log(`Built standalone AMO: ${binaryPath} (${size} MB, ${process.env.AMO_TARGET_ARCH || process.arch})`);
