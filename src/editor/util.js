function inRanges(cp, ranges) {
  let lo = 0, hi = ranges.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const [a, b] = ranges[mid];
    if (cp < a) hi = mid - 1;
    else if (cp > b) lo = mid + 1;
    else return true;
  }
  return false;
}

export function charWidth(ch) {
  if (ch == null || ch === '') return 0;
  const cp = typeof ch === 'number' ? ch : ch.codePointAt(0);
  if (cp === 0) return 0;
  if (cp < 32 || (cp >= 0x7f && cp < 0xa0)) return 0;
  if (inRanges(cp, ZERO_WIDTH)) return 0;
  if (inRanges(cp, WIDE)) return 2;
  return 1;
}

export function stringWidth(str) {
  let w = 0;
  for (const ch of str) w += charWidth(ch);
  return w;
}

export function toCPs(str) {
  return Array.from(str == null ? '' : String(str));
}

export function sliceCPs(str, start, end) {
  return toCPs(str).slice(start, end).join('');
}

export function cpLength(str) {
  let n = 0;
  for (const _ of str) n++;
  return n;
}

export function clamp(v, lo, hi) {
  return v < lo ? lo : v > hi ? hi : v;
}

export function escapeRegex(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

export function truncateWidth(str, maxWidth) {
  if (stringWidth(str) <= maxWidth) return str;
  let out = '';
  let w = 0;
  for (const ch of str) {
    const cw = charWidth(ch);
    if (w + cw > maxWidth) break;
    out += ch;
    w += cw;
  }
  return out;
}

export function padWidth(str, width) {
  const w = stringWidth(str);
  return w >= width ? str : str + ' '.repeat(width - w);
}
